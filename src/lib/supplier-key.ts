const LETTER_FOLD: Record<string, string> = {
  æ: "ae",
  ø: "o",
  å: "a",
  ß: "ss",
  œ: "oe",
  đ: "d",
  ł: "l",
  þ: "th",
};

function foldLatin(value: string): string {
  const lowered = value.toLowerCase().replace(/[æøåßœđłþ]/g, (ch) => LETTER_FOLD[ch] ?? ch);
  return lowered.normalize("NFD").replace(/[\u0300-\u036f]/g, "");
}

/** ASCII slug shared by every customer who typed the same supplier. */
export function normalizeSupplierName(name: string): string {
  const slug = foldLatin(name)
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return slug || "unknown";
}

export function countryCode(country: string): string {
  const trimmed = country.trim();
  if (trimmed in COUNTRY_CODES) {
    return COUNTRY_CODES[trimmed as Country];
  }
  const slug = foldLatin(trimmed).replace(/[^a-z]/g, "").slice(0, 8).toUpperCase();
  return slug || "XX";
}

/**
 * Cache key for news collection. Example: Maersk + Denmark → `maersk|DK`.
 * Not a foreign key — many customer Supplier rows share one key.
 */
export function supplierKey(name: string, country: string): string {
  return `${normalizeSupplierName(name)}|${countryCode(country)}`;
}

/** Headline key used to drop aggregator republishes that do not share a URL. */
export function normalizeTitleForDedupe(title: string): string {
  let text = foldLatin(title);
  const parts = text.split(" - ");
  if (parts.length >= 2) {
    parts.pop();
    text = parts.join(" - ");
  }
  return text.replace(/[^a-z0-9]+/g, " ").trim().replace(/ +/g, " ");
}

export function countryCodesCoverCatalog(): boolean {
  return COUNTRIES.every((country) => COUNTRY_CODES[country]?.length >= 2);
}
